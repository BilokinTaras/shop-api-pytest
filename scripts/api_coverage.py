"""API coverage: operations in the pinned OpenAPI specs vs operations the suite actually calls.

Usage: make coverage   (runs the suite with call recording, then writes docs/api-coverage.md)
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
METHODS = {"get", "post", "put", "patch", "delete"}


def load_operations(spec: Path) -> list[tuple[str, str, str]]:
    doc = yaml.safe_load(spec.read_text(encoding="utf-8"))
    ops = []
    for path, item in doc["paths"].items():
        for method, op in item.items():
            if method in METHODS:
                tag = (op.get("tags") or ["(untagged)"])[0]
                ops.append((method.upper(), path, tag))
    return ops


def matcher(path: str) -> re.Pattern[str]:
    return re.compile(
        "^" + re.sub(r"\{[^}]+\}", "[^/]+", re.escape(path).replace(r"\{", "{").replace(r"\}", "}")) + "$"
    )


def main(record_dir: str) -> None:
    calls = set()
    for file in Path(record_dir).glob("calls-*.txt"):
        calls |= {line.strip() for line in file.read_text(encoding="utf-8").splitlines() if line.strip()}
    out = [
        "# API coverage",
        "",
        f"Generated by `make coverage` on {datetime.now(UTC).date()} from a full run of the suite "
        "(every HTTP call recorded) against the operations in `contracts/openapi/`.",
        "An operation counts as covered when at least one test calls it; Schemathesis fuzzing comes on top "
        "(all 33 Store `GET` operations and 15 cart operations, see contract-findings.md).",
        "",
    ]
    for name in ("store", "admin"):
        ops = load_operations(ROOT / "contracts" / "openapi" / f"{name}.openapi.yaml")
        covered = []
        for method, path, tag in ops:
            rx = matcher(path)
            if any(c.split(" ", 1)[0] == method and rx.match(c.split(" ", 1)[1]) for c in calls):
                covered.append((method, path, tag))
        by_tag: defaultdict[str, list[int]] = defaultdict(lambda: [0, 0])
        for _method, _path, tag in ops:
            by_tag[tag][1] += 1
        for _, _, tag in covered:
            by_tag[tag][0] += 1
        pct = 100 * len(covered) / len(ops)
        out += [
            f"## {name.title()} API: {len(covered)} / {len(ops)} operations ({pct:.0f} %)",
            "",
            "| Tag | Covered | Total |",
            "|---|---:|---:|",
        ]
        for tag, (c, t) in sorted(by_tag.items(), key=lambda kv: (-kv[1][0], kv[0])):
            if c or name == "store":
                out.append(f"| {tag} | {c} | {t} |")
        if name == "admin":
            out.append(f"| *(other admin tags)* | 0 | {sum(t for c, t in by_tag.values() if c == 0)} |")
        out += ["", "<details><summary>Covered operations</summary>", ""]
        out += [f"- `{m} {p}`" for m, p, _ in sorted(covered, key=lambda x: (x[1], x[0]))]
        out += ["", "</details>", ""]
    (ROOT / "docs" / "api-coverage.md").write_text("\n".join(out), encoding="utf-8")
    print("api-coverage: docs/api-coverage.md")


if __name__ == "__main__":
    main(sys.argv[1])
